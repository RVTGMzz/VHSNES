def points(pattern,x,y):
    return {(x+dx,y+dy) for dy,row in enumerate(pattern.split('/')) for dx,b in enumerate(row) if b=='1'}
def layers(ch):
    if ch==' ': return dict(body=set(),modifier=set(),tone=set())
    if ch in PUNCT:
        p,x,y=PUNCT[ch];return dict(body=points(p,x,y),modifier=set(),tone=set())
    seq=ud.normalize('NFD',ch);base=seq[0];marks=set(seq[1:])
    if ch in 'đĐ':base='d' if ch=='đ' else 'D'
    rows=(LOWER|UPPER|DIGITS)[base].split('/')
    if base.isupper() and marks:rows=[rows[i] for i in (0,1,3,5,6)]
    y=4 if (base.islower() and base not in 'bdfhklt') or (base.isupper() and marks) else 2
    if base=='y' and '\u0323' in marks:rows=['10001','10001','01111','00001','01110']
    body=points('/'.join(rows),3,y);modifier=set();tone=set()
    if base in 'ij' and not marks.intersection(TONES):body.add((5,2))
    if ch in 'đĐ':modifier=points('1111',5 if ch=='đ' else 2,4 if ch=='đ' else 6)
    stacked=bool(marks.intersection({'\u0302','\u0306'}))
    if '\u0302' in marks:modifier|=points('00100/01010',3,1)
    if '\u0306' in marks:modifier|=points('10001/01110',3,1)
    if '\u031b' in marks:modifier|={(9,2),(9,3),(8,4),(7,4)}
    for mark,pat in TONES.items():
        if mark in marks:tone|=points(pat,7 if stacked else (3 if mark=='\u0303' else 4),0)
    if '\u0323' in marks:tone.add((5,10))
    return dict(body=body,modifier=modifier,tone=tone)
def glyph(ch):
    pts=set().union(*layers(ch).values())
    if any(not(0<=x<12 and 0<=y<11) for x,y in pts):raise ValueError(ch)
    bits=''.join('1' if (x,y) in pts else '0' for y in range(12) for x in range(12))
    return int(bits,2).to_bytes(18,'big').hex()
